//! Imports the analysis Decomp generated from Ghidra (`ausgabe/`) into `knowledge/analysis/`.
//!
//! Function files are `<header><body>`: the header is Decomp's `kopf` (`/* @adresse ...` up to and including
//! the line ` */`), the body follows with no separator. The body is stored exactly as found.

use std::collections::{BTreeMap, HashMap};
use std::path::{Path, PathBuf};

use serde::Deserialize;

use super::{Ctx, MigrateError, io, read, translate_address};
use crate::address::Address;
use crate::analysis::{
    AccessKind, Analysis, AnalyzedFunction, CallEdge, DataAccess, Provider, StringItem,
    knowledge_hash, today,
};
use crate::workspace::Workspace;

/// The header's last line. Decomp writes it with LF; a git checkout with `autocrlf` turns it into CRLF.
const HEADER_END: &str = "\n */";

/// Length of `kopf`'s output including the line break after ` */`; the body starts right after it.
fn header_len(text: &str) -> Option<usize> {
    let after = text.find(HEADER_END)? + HEADER_END.len();
    let rest = &text[after..];
    if rest.starts_with("\r\n") {
        Some(after + 2)
    } else if rest.starts_with('\n') {
        Some(after + 1)
    } else {
        None
    }
}
const ERROR_PREFIX: &str = "/* Dekompilieren fehlgeschlagen: ";
const TABLE_RULE: &str = "| --- |";

/// Entries of `ausgabe/` that are imported (when `funktionen/` exists).
const IMPORTED: [&str; 4] = ["funktionen", "aufrufe.json", "strings.md", "globale.md"];

/// Everything read from `ausgabe/`, ready to be saved once the target workspace exists.
pub(super) struct Imported {
    provider: Provider,
    functions: Vec<AnalyzedFunction>,
    bodies: Vec<(Address, String)>,
    calls: Vec<CallEdge>,
    strings: Vec<StringItem>,
    accesses: Vec<DataAccess>,
}

#[derive(Deserialize)]
struct CallsFile {
    kanten: Vec<RawEdge>,
}

#[derive(Deserialize)]
struct RawEdge {
    von: String,
    stelle: String,
    ziel: String,
}

/// Reads a text file; decovery stores LF only, so CRLF (git autocrlf checkouts, Ghidra output) becomes LF.
fn read_lf(path: &Path) -> Result<String, MigrateError> {
    Ok(read(path)?.replace("\r\n", "\n"))
}

fn invalid(path: &Path, what: impl Into<String>) -> MigrateError {
    MigrateError::Invalid {
        key: path.display().to_string(),
        value: what.into(),
    }
}

fn address(path: &Path, text: &str) -> Result<Address, MigrateError> {
    translate_address(text.trim()).ok_or_else(|| invalid(path, format!("bad address `{text}`")))
}

fn skip_reason(name: &str) -> &'static str {
    match name {
        "index.md" => "function index; regenerated by decovery",
        "stand.json" => "status counters; regenerated by decovery",
        "laufzeit.md" => "runtime report; regenerated from knowledge/runs",
        "decomp-symbole.json" => "Decomp's dump of Ghidra symbols; not part of the analysis",
        _ => "generated output; not imported",
    }
}

/// Lists what of `ausgabe/` is not imported. Without `funktionen/` nothing is imported.
pub(super) fn plan_skips(from: &Path, cx: &mut Ctx) -> Result<(), MigrateError> {
    let dir = from.join("ausgabe");
    if !dir.is_dir() {
        return Ok(());
    }
    let importing = dir.join("funktionen").is_dir();
    for path in sorted_entries(&dir)? {
        let name = path
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        let imported = IMPORTED.contains(&name.as_str());
        if importing && imported {
            continue;
        }
        let reason = if imported {
            "analysis is imported only together with ausgabe/funktionen"
        } else {
            skip_reason(&name)
        };
        cx.skipped.insert(format!("ausgabe/{name}: {reason}"));
    }
    Ok(())
}

fn sorted_entries(dir: &Path) -> Result<Vec<PathBuf>, MigrateError> {
    let mut paths = Vec::new();
    for entry in std::fs::read_dir(dir).map_err(|e| io(dir, e))? {
        paths.push(entry.map_err(|e| io(dir, e))?.path());
    }
    paths.sort();
    Ok(paths)
}

/// Decomp's file-name stem for an address: `va_0001A2B0`, `rel_0001_0010`.
fn file_stem(at: Address) -> Option<String> {
    match at {
        Address::Flat(v) => Some(format!("va_{v:08X}")),
        Address::Seg { seg, off } => Some(format!("rel_{seg:04X}_{off:04X}")),
        _ => None,
    }
}

struct ParsedFunction {
    function: AnalyzedFunction,
    body: String,
    name: Option<String>,
}

/// Splits `<header><body>` and reads range and sizes from the `@adresse` line.
fn parse_function(path: &Path, text: &str) -> Result<ParsedFunction, MigrateError> {
    let bad = |what: &str| invalid(path, what.to_string());
    let rest = text
        .strip_prefix("/* @adresse")
        .ok_or_else(|| bad("function file does not start with `/* @adresse`"))?;
    let header_len =
        header_len(text).ok_or_else(|| bad("function header is not terminated by a ` */` line"))?;
    let line = rest.lines().next().unwrap_or("").trim();
    let (start, after) = line
        .split_once(" .. ")
        .ok_or_else(|| bad("`@adresse` has no range"))?;
    let (end, sizes) = after
        .split_once(" (")
        .ok_or_else(|| bad("`@adresse` has no size"))?;
    let sizes = sizes
        .split_once(')')
        .ok_or_else(|| bad("`@adresse` size is not closed"))?
        .0;
    let number = |part: &str, suffix: &str| -> Option<u32> {
        part.strip_suffix(suffix)?.trim().parse().ok()
    };
    let parts: Vec<&str> = sizes.split(", ").collect();
    let body_size = match parts.first() {
        Some(first) if first.ends_with(" Bytes Spanne") => parts
            .get(1)
            .and_then(|p| number(p, " im Rumpf"))
            .ok_or_else(|| bad("`@adresse` has a span but no `im Rumpf` size"))?,
        Some(first) => number(first, " Bytes").ok_or_else(|| bad("`@adresse` size not numeric"))?,
        None => return Err(bad("`@adresse` size is empty")),
    };
    let start = address(path, start)?;
    let end = address(path, end)?;
    let body = text[header_len..].to_string();
    let mut function = AnalyzedFunction::new(start, end, body_size);
    if let Some(error) = body.strip_prefix(ERROR_PREFIX) {
        let message = error.split("*/").next().unwrap_or(error).trim_end();
        function.decompile_error = Some(message.to_string());
    }
    let name = path
        .file_stem()
        .and_then(|s| s.to_str())
        .zip(file_stem(start))
        .and_then(|(stem, prefix)| stem.strip_prefix(&format!("{prefix}_")))
        .map(str::to_string);
    Ok(ParsedFunction {
        function,
        body,
        name,
    })
}

/// Splits a table row at unescaped `|`; `\|` stays inside the cell. Returns the cells between the outer bars.
fn split_row(line: &str) -> Vec<&str> {
    let bytes = line.as_bytes();
    let mut cells = Vec::new();
    let mut from = 0;
    let mut i = 0;
    while i < bytes.len() {
        match bytes[i] {
            b'\\' if bytes.get(i + 1) == Some(&b'|') => i += 2,
            b'|' => {
                cells.push(&line[from..i]);
                from = i + 1;
                i += 1;
            }
            _ => i += 1,
        }
    }
    cells.push(&line[from..]);
    if cells.len() >= 2 {
        cells.remove(0);
        cells.pop();
    }
    cells
}

/// Strips exactly one space on each side, as Decomp pads cells.
fn cell(raw: &str) -> &str {
    let raw = raw.strip_prefix(' ').unwrap_or(raw);
    raw.strip_suffix(' ').unwrap_or(raw)
}

/// Reverses Decomp's `|` -> `\|` and newline -> `\n` escaping.
fn unescape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match (c, chars.peek()) {
            ('\\', Some('|')) => {
                out.push('|');
                chars.next();
            }
            ('\\', Some('n')) => {
                out.push('\n');
                chars.next();
            }
            _ => out.push(c),
        }
    }
    out
}

/// The data rows of a Decomp table (everything after the `| --- |` rule).
fn table_rows(text: &str) -> Vec<&str> {
    let mut lines = text.split('\n');
    lines
        .by_ref()
        .find(|l| l.starts_with(TABLE_RULE))
        .map(|_| lines.filter(|l| l.starts_with('|')).collect())
        .unwrap_or_default()
}

fn parse_strings(path: &Path, text: &str) -> Result<Vec<StringItem>, MigrateError> {
    let mut items = Vec::new();
    for row in table_rows(text) {
        let cells = split_row(row);
        let [at, text, users] = cells[..] else {
            return Err(invalid(
                path,
                format!("string row has {} cells", cells.len()),
            ));
        };
        let users = cell(users);
        let mut list = Vec::new();
        if !users.is_empty() {
            for user in users.split(", ") {
                list.push(address(path, user.split(' ').next().unwrap_or(user))?);
            }
        }
        items.push(StringItem::new(
            address(path, cell(at))?,
            unescape(cell(text)),
            list,
        ));
    }
    Ok(items)
}

/// Returns the accesses and the number of listed names that could not be mapped to a function.
fn parse_globals(
    path: &Path,
    text: &str,
    names: &HashMap<String, Vec<Address>>,
) -> Result<(Vec<DataAccess>, u32), MigrateError> {
    let mut accesses = Vec::new();
    let mut unresolved = 0;
    for row in table_rows(text) {
        let cells = split_row(row);
        let [at, _name, reads, writes] = cells[..] else {
            return Err(invalid(
                path,
                format!("global row has {} cells", cells.len()),
            ));
        };
        let at = address(path, cell(at))?;
        for (column, kind) in [(reads, AccessKind::Read), (writes, AccessKind::Write)] {
            let column = cell(column);
            if column.is_empty() {
                continue;
            }
            for name in column.split(", ") {
                match names.get(name).map(Vec::as_slice) {
                    Some([function]) => accesses.push(DataAccess::new(*function, at, kind)),
                    _ => unresolved += 1,
                }
            }
        }
    }
    Ok((accesses, unresolved))
}

fn provider_version(from: &Path) -> String {
    let text = std::fs::read_to_string(from.join("cache/ghidra/meta.json")).ok();
    let version = text
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .and_then(|v| v.get("ghidra")?.as_str().map(str::to_string));
    version.map_or_else(|| "unknown".to_string(), |v| format!("ghidra {v}"))
}

/// Reads `ausgabe/` of the Decomp workspace; `None` when it has no `funktionen/` tree.
pub(super) fn read_output(from: &Path, cx: &mut Ctx) -> Result<Option<Imported>, MigrateError> {
    let dir = from.join("ausgabe");
    let functions_dir = dir.join("funktionen");
    if !functions_dir.is_dir() {
        return Ok(None);
    }
    let mut functions = Vec::new();
    let mut bodies = Vec::new();
    let mut names: HashMap<String, Vec<Address>> = HashMap::new();
    let mut seen: BTreeMap<Address, PathBuf> = BTreeMap::new();
    for segment in sorted_entries(&functions_dir)? {
        if !segment.is_dir() {
            continue;
        }
        for file in sorted_entries(&segment)? {
            if file.extension().and_then(|e| e.to_str()) != Some("c") {
                continue;
            }
            let parsed = parse_function(&file, &read_lf(&file)?)?;
            let start = parsed.function.start;
            if let Some(first) = seen.insert(start, file.clone()) {
                return Err(invalid(&file, format!("same start as {}", first.display())));
            }
            if let Some(name) = parsed.name {
                names.entry(name).or_default().push(start);
            }
            bodies.push((start, parsed.body));
            functions.push(parsed.function);
        }
    }

    let mut calls = Vec::new();
    let calls_path = dir.join("aufrufe.json");
    if calls_path.is_file() {
        let file: CallsFile = serde_json::from_str(&read(&calls_path)?)
            .map_err(|e| invalid(&calls_path, e.to_string()))?;
        for edge in file.kanten {
            calls.push(CallEdge::new(
                address(&calls_path, &edge.stelle)?,
                address(&calls_path, &edge.von)?,
                address(&calls_path, &edge.ziel)?,
            ));
        }
    }
    let strings_path = dir.join("strings.md");
    let strings = if strings_path.is_file() {
        parse_strings(&strings_path, &read_lf(&strings_path)?)?
    } else {
        Vec::new()
    };
    let globals_path = dir.join("globale.md");
    let mut accesses = Vec::new();
    if globals_path.is_file() {
        let (found, unresolved) = parse_globals(&globals_path, &read_lf(&globals_path)?, &names)?;
        accesses = found;
        if unresolved > 0 {
            cx.skipped.insert(format!(
                "ausgabe/globale.md: {unresolved} accesses named a function that is missing or ambiguous in ausgabe/funktionen; not imported"
            ));
        }
    }
    Ok(Some(Imported {
        provider: Provider::new("decomp-import", provider_version(from)),
        functions,
        bodies,
        calls,
        strings,
        accesses,
    }))
}

impl Imported {
    /// Saves through the Task 2 API under the workspace lock; returns the number of functions.
    pub(super) fn save(self, to: &Path, target_sha256: &str) -> Result<u32, MigrateError> {
        let ws = Workspace::open(to)?;
        let lock = ws.lock(std::time::Duration::from_secs(10))?;
        let hash = knowledge_hash(to)?;
        let mut analysis = Analysis::new(self.provider, target_sha256, hash, today());
        let count = u32::try_from(self.functions.len()).unwrap_or(u32::MAX);
        analysis.functions = self.functions;
        analysis.calls = self.calls;
        analysis.strings = self.strings;
        analysis.data_accesses = self.accesses;
        analysis.save(to, &lock)?;
        for (start, body) in &self.bodies {
            Analysis::save_decompiled(to, *start, body, &lock)?;
        }
        Ok(count)
    }
}


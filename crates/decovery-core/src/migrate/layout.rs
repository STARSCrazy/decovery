//! Directory-level part of the migration: what is copied, what is skipped and why.

use std::path::{Path, PathBuf};

use super::decomp_format::{dirs, keys};
use super::{Ctx, MigrateError, create_dir, io};

/// Files and trees to copy, relative to the source and target roots.
#[derive(Default)]
pub(super) struct Copies {
    /// (source path, target path relative to the workspace root)
    pub(super) items: Vec<(PathBuf, String)>,
}

impl Copies {
    pub(super) fn add(&mut self, source: PathBuf, target: impl Into<String>) {
        self.items.push((source, target.into()));
    }
}

/// True for `C:/x`, `/x` and `\x` regardless of the host platform.
fn is_absolute(path: &str) -> bool {
    path.starts_with('/') || path.starts_with('\\') || path.as_bytes().get(1) == Some(&b':')
}

fn skip(cx: &mut Ctx, path: &str, reason: &str) {
    cx.skipped.insert(format!("{path}: {reason}"));
}

/// Rewrites `[target] file` and plans the copy of Decomp's game directory.
pub(super) fn plan_target(file: &mut String, from: &Path, copies: &mut Copies, cx: &mut Ctx) {
    let game = from.join(dirs::GAME);
    let relative = file
        .strip_prefix(&format!("{}/", dirs::GAME))
        .or_else(|| file.strip_prefix(&format!("{}\\", dirs::GAME)))
        .map(str::to_string);
    if let Some(rest) = relative {
        *file = format!("target/{rest}");
        if game.is_dir() {
            copies.add(game, "target");
        }
        return;
    }
    if !is_absolute(file) {
        cx.unmapped
            .insert(format!("{}.{}={file}", keys::TARGET, keys::FILE));
    }
    if game.is_dir() {
        let reason = if is_absolute(file) {
            "target binary is referenced by an absolute path outside the workspace".to_string()
        } else {
            format!("target file is not inside {}/", dirs::GAME)
        };
        skip(cx, dirs::GAME, &reason);
    }
}

/// Plans Decomp's rebuild sources -> `src/`, its rebuild objects -> `cache/rebuild/obj/` and lists the rest as skipped.
pub(super) fn plan_trees(
    from: &Path,
    copies: &mut Copies,
    cx: &mut Ctx,
) -> Result<(), MigrateError> {
    let rebuild = from.join(dirs::REBUILD);
    if rebuild.is_dir() {
        copies.add(rebuild, "src");
    }
    super::analysis_import::plan_skips(from, cx)?;
    let cache = from.join(dirs::CACHE);
    if !cache.is_dir() {
        return Ok(());
    }
    for name in sorted_names(&cache)? {
        if name != dirs::REBUILD {
            skip(
                cx,
                &format!("{}/{name}", dirs::CACHE),
                "Decomp cache (generated, backend-specific)",
            );
            continue;
        }
        let rebuild_cache = cache.join(dirs::REBUILD);
        for entry in sorted_names(&rebuild_cache)? {
            if entry == "obj" {
                plan_objects(&rebuild_cache.join("obj"), copies, cx)?;
            } else {
                skip(
                    cx,
                    &format!("{}/{}/{entry}", dirs::CACHE, dirs::REBUILD),
                    "Decomp rebuild cache (attempts, archive, logbook); decovery keeps its own",
                );
            }
        }
    }
    Ok(())
}

fn plan_objects(dir: &Path, copies: &mut Copies, cx: &mut Ctx) -> Result<(), MigrateError> {
    if !dir.is_dir() {
        return Ok(());
    }
    let mut other_extensions = std::collections::BTreeSet::new();
    for name in sorted_names(dir)? {
        let path = dir.join(&name);
        match name.rsplit_once('.') {
            Some((_, ext)) if ext.eq_ignore_ascii_case("obj") && path.is_file() => {
                copies.add(path, format!("cache/rebuild/obj/{name}"));
            }
            Some((_, ext)) => {
                other_extensions.insert(ext.to_string());
            }
            None => {
                other_extensions.insert(String::new());
            }
        }
    }
    for ext in other_extensions {
        skip(
            cx,
            &format!("{}/{}/obj/*.{ext}", dirs::CACHE, dirs::REBUILD),
            "build metadata next to the objects; regenerated by the rebuild",
        );
    }
    Ok(())
}

fn sorted_names(dir: &Path) -> Result<Vec<String>, MigrateError> {
    let mut names = Vec::new();
    for entry in std::fs::read_dir(dir).map_err(|e| io(dir, e))? {
        let entry = entry.map_err(|e| io(dir, e))?;
        names.push(entry.file_name().to_string_lossy().into_owned());
    }
    names.sort();
    Ok(names)
}

/// Copies a file or a directory tree; returns the number of files.
pub(super) fn copy_item(source: &Path, target: &Path) -> Result<u32, MigrateError> {
    if source.is_dir() {
        create_dir(target)?;
        let mut count = 0;
        for name in sorted_names(source)? {
            count += copy_item(&source.join(&name), &target.join(&name))?;
        }
        return Ok(count);
    }
    if let Some(parent) = target.parent() {
        create_dir(parent)?;
    }
    std::fs::copy(source, target).map_err(|e| io(source, e))?;
    Ok(1)
}


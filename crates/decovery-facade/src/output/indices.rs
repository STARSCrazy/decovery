//! Index files next to the function files and the status counts.

use std::collections::BTreeMap;

use decovery_core::{AccessKind, Address, ClaimSource, Confidence, RebuildResult};
use serde::{Deserialize, Serialize};

use super::{Context, OUTPUT_DIR, access_rank, files, header::kebab, sort_accesses};
use crate::{FacadeError, Session};

const GENERATED_MD: &str = "<!-- generated by decovery; do not edit -->";
const STALE_LINE: &str = "Analysis is older than the knowledge; run `decovery analyze`.";

/// Naming and rebuild state over all analyzed functions (`output/status.json`, `decovery status`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct StatusCounts {
    pub functions: u32,
    /// Functions with an active name.
    pub named: u32,
    /// Named functions whose name is confirmed.
    pub confirmed: u32,
    /// Named functions whose name is assumed (`named - confirmed`).
    pub assumed: u32,
    pub unnamed: u32,
    /// Named functions whose name comes from a signature match.
    pub by_signature: u32,
    pub rebuild_identical: u32,
    pub rebuild_differs: u32,
    pub rebuild_error: u32,
    /// Functions without a rebuild record. A record with an unknown result is counted nowhere.
    pub rebuild_not_tried: u32,
}

/// Counts naming and rebuild state of the session's functions.
pub fn status_counts(session: &Session) -> StatusCounts {
    let mut c = StatusCounts::default();
    let rebuild: std::collections::HashMap<Address, RebuildResult> = session
        .rebuild
        .iter()
        .map(|r| (r.address, r.result))
        .collect();
    for f in &session.analysis.functions {
        c.functions += 1;
        match session.symbol_at(f.start) {
            Some(s) => {
                c.named += 1;
                c.confirmed += u32::from(s.confidence == Confidence::Confirmed);
                c.by_signature += u32::from(s.source == ClaimSource::Signature);
            }
            None => c.unnamed += 1,
        }
        match rebuild.get(&f.start) {
            None => c.rebuild_not_tried += 1,
            Some(RebuildResult::Identical) => c.rebuild_identical += 1,
            Some(RebuildResult::Differs) => c.rebuild_differs += 1,
            Some(RebuildResult::Error) => c.rebuild_error += 1,
            Some(_) => {}
        }
    }
    c.assumed = c.named - c.confirmed;
    c
}

/// Rewrites `index.md`, `calls.json`, `strings.md`, `globals.md` and `status.json` (unchanged files stay).
pub(crate) fn write_indices(cx: &Context<'_>) -> Result<(), FacadeError> {
    let out = cx.session.workspace.root.join(OUTPUT_DIR);
    let counts = status_counts(cx.session);
    files::write_if_changed(&out.join("index.md"), &index_md(cx, &counts))?;
    files::write_if_changed(&out.join("calls.json"), &calls_json(cx)?)?;
    files::write_if_changed(&out.join("strings.md"), &strings_md(cx))?;
    files::write_if_changed(&out.join("globals.md"), &globals_md(cx))?;
    files::write_if_changed(&out.join("status.json"), &status_json(&counts, cx.stale)?)?;
    Ok(())
}

fn index_md(cx: &Context<'_>, c: &StatusCounts) -> String {
    let mut lines = vec![GENERATED_MD.to_string()];
    if cx.stale {
        lines.push(STALE_LINE.to_string());
        lines.push(String::new());
    }
    lines.extend([
        "# Function index".to_string(),
        String::new(),
        format!(
            "Status: {}/{} named ({} confirmed, {} assumed)",
            c.named, c.functions, c.confirmed, c.assumed
        ),
        String::new(),
    ]);
    if !cx.session.rebuild.is_empty() {
        lines.push(format!(
            "Rebuild: {} identical, {} differs, {} error",
            c.rebuild_identical, c.rebuild_differs, c.rebuild_error
        ));
        lines.push(String::new());
    }
    lines.push("| Address | Name | Size | Called by | Status | File |".to_string());
    lines.push("| --- | --- | --- | --- | --- | --- |".to_string());
    for f in cx.functions() {
        let mut callers: Vec<Address> = cx.callers(f.start).iter().map(|e| e.caller).collect();
        callers.dedup();
        let status = cx
            .named(f.start)
            .map_or_else(|| "unnamed".to_string(), |s| kebab(&s.confidence));
        lines.push(format!(
            "| {} | {} | {} | {} | {status} | [c]({}) |",
            f.start,
            cx.display_name(f.start),
            f.body_size,
            callers.len(),
            files::link_path(cx, f.start)
        ));
    }
    lines.join("\n") + "\n"
}

#[derive(Serialize)]
struct Edge {
    caller: Address,
    site: Address,
    callee: Address,
}

#[derive(Serialize)]
struct CallsFile {
    schema: u32,
    edges: Vec<Edge>,
}

fn json_text<T: Serialize>(value: &T) -> Result<String, FacadeError> {
    serde_json::to_string_pretty(value)
        .map(|t| t + "\n")
        .map_err(|e| FacadeError::Invalid(format!("cannot serialize output: {e}")))
}

fn calls_json(cx: &Context<'_>) -> Result<String, FacadeError> {
    let edges = cx
        .calls()
        .into_iter()
        .map(|e| Edge {
            caller: e.caller,
            site: e.site,
            callee: e.callee,
        })
        .collect();
    json_text(&CallsFile { schema: 1, edges })
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', "\\n")
}

fn strings_md(cx: &Context<'_>) -> String {
    let mut lines = vec![
        GENERATED_MD.to_string(),
        "# Strings".to_string(),
        String::new(),
        "| Address | Text | Used by |".to_string(),
        "| --- | --- | --- |".to_string(),
    ];
    let mut strings: Vec<_> = cx.session.analysis.strings.iter().collect();
    strings.sort_by_key(|s| s.address);
    for s in strings {
        let users: Vec<String> = s
            .users
            .iter()
            .map(|u| format!("{u} {}", cx.display_name(*u)))
            .collect();
        lines.push(format!(
            "| {} | {} | {} |",
            s.address,
            cell(&s.text),
            users.join(", ")
        ));
    }
    lines.join("\n") + "\n"
}

fn globals_md(cx: &Context<'_>) -> String {
    let mut lines = vec![
        GENERATED_MD.to_string(),
        "# Globals".to_string(),
        String::new(),
        "| Address | Name | Reads | Writes |".to_string(),
        "| --- | --- | --- | --- |".to_string(),
    ];
    let mut accesses: Vec<_> = cx.session.analysis.data_accesses.iter().collect();
    sort_accesses(&mut accesses);
    let mut by_variable: BTreeMap<Address, Vec<_>> = BTreeMap::new();
    for g in accesses {
        by_variable.entry(g.address).or_default().push(g);
    }
    for (var, accesses) in by_variable {
        let name = cx.named(var).map_or("", |s| s.name.as_str());
        let names = |kind: AccessKind| {
            accesses
                .iter()
                .filter(|g| access_rank(g.kind) == access_rank(kind))
                .map(|g| cx.display_name(g.function))
                .collect::<Vec<_>>()
                .join(", ")
        };
        lines.push(format!(
            "| {var} | {name} | {} | {} |",
            names(AccessKind::Read),
            names(AccessKind::Write)
        ));
    }
    lines.join("\n") + "\n"
}

#[derive(Serialize)]
struct StatusFile<'a> {
    schema: u32,
    #[serde(flatten)]
    counts: &'a StatusCounts,
    analysis_stale: bool,
}

fn status_json(counts: &StatusCounts, analysis_stale: bool) -> Result<String, FacadeError> {
    json_text(&StatusFile {
        schema: 1,
        counts,
        analysis_stale,
    })
}
